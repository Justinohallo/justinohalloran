// Turns src/tokens.json into src/styles/tokens.css.
// Light values live in a Tailwind v4 @theme block (so they generate utilities like bg-surface);
// dark values override the same custom properties under prefers-color-scheme.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(resolve(root, 'src/tokens.json'), 'utf8'))

const vars = (obj, prefix) =>
  Object.entries(obj).map(([k, v]) => `  --${prefix}-${k}: ${v};`).join('\n')

const css = `/* Generated by scripts/build-tokens.mjs from src/tokens.json. Do not edit. */
@theme {
${vars(tokens.color.light, 'color')}
${vars(tokens.font, 'font')}
${vars(tokens.radius, 'radius')}
${vars(tokens.measure, 'container')}
}

@media (prefers-color-scheme: dark) {
  :root {
${vars(tokens.color.dark, 'color').replace(/^/gm, '  ')}
  }
}
`

const out = resolve(root, 'src/styles/tokens.css')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, css)
console.log(`tokens: wrote ${Object.keys(tokens.color.light).length} colors to src/styles/tokens.css`)
